"""Google Sheets 取回的二維表 → 一維內容清單。

三支內容抽取器（吃啥、酷酷的諧音梗、冒險台詞）各自寫了一份幾乎相同的巢狀
comprehension，而「要不要跳過第一列」三支寫得不一樣（CODE_REVIEW P2-29）。

2026-08-21 直接打 9091 核對三張表的實際形狀，結論是**那個不一致是對的**：

| 工作表 | 第 0 列是什麼 | 要跳過嗎 |
| --- | --- | --- |
| 吃啥 | 分類標題（飯／飯糰／燴飯…），第 1 列起才是餐點 | 要 |
| 酷酷的諧音梗 | 空列（回傳 `[]`），第 1 列起才是內容 | 不要 |
| 冒險台詞 | 第一句台詞本身 | 不要 |

所以這裡不去「統一」行為，而是把「跳或不跳」變成呼叫端必須明寫的參數。
下一個人看到三支寫得不一樣時，看到的是三個明確的 skip_header，
而不是一個看起來像漏掉的 `[1:]`。

（諧音梗那張表就算跳過第 0 列也剛好不會出事——它是空列——但依賴這件事很危險：
那一列哪天被填上內容，就會安靜地被吃掉，而且沒有任何錯誤。）
"""


def collect_cells(rows: list[list[str]] | None, *, skip_header: bool) -> list[str]:
    """把整張表攤平成一維清單；空格與只有空白的格子一律丟掉。

    skip_header 沒有預設值是刻意的：這個決定必須看過那張表才能下，
    不該有人靠「預設應該是對的」帶過去。

    rows 拿到 None（微服務回了沒有 data 的 JSON）時回空 list，
    讓呼叫端「池子還是空的」自己觸發下一次重抓，而不是在這裡炸掉——
    抓內容表是在處理觀眾訊息的路徑上，炸掉會連招呼與獎勵一起沒有。
    """
    if not rows:
        return []
    body = rows[1:] if skip_header else rows
    return [cell.strip() for row in body for cell in row if cell and cell.strip()]
